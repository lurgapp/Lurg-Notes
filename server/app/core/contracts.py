"""Стабильные границы движков Lurg Core.

Конкретные provider-реализации подключаются dependency injection и не должны
проникать в доменные модели.
"""
from typing import Any, AsyncIterator, Protocol
from uuid import UUID

class IdentityEngine(Protocol):
    async def resolve(self, access_token: str) -> UUID: ...

class MemoryEngine(Protocol):
    async def ingest(self, owner_id: UUID, content: str) -> dict[str, Any]: ...
    async def forget(self, owner_id: UUID, resource_id: UUID) -> None: ...

class PermissionEngine(Protocol):
    async def allowed(self, subject_id: UUID, action: str, resource_id: UUID) -> bool: ...

class AIEngine(Protocol):
    provider_name: str
    text_model: str
    embedding_model: str

    async def extract_graph(self, content: str) -> dict[str, Any]: ...
    async def classify_personal_query(self, content: str) -> dict[str, Any]: ...
    async def extract_repository_intelligence(self, content: str) -> dict[str, Any]: ...
    async def structured_json(self, instruction: str, content: str, *, max_tokens: int = 1000, temperature: float = 0.2) -> dict[str, Any]: ...
    async def embed(self, content: str, purpose: str) -> list[float]: ...
    async def answer(self, question: str, context: list[dict[str, Any]]) -> str: ...
    async def stream_answer(self, question: str, context: dict[str, Any], history: list[dict[str, str]] | None = None, *, mode: str = "general", complex_query: bool = False) -> AsyncIterator[str]: ...

class InternetSearchEngine(Protocol):
    async def search(self, query: str, language: str, limit: int) -> list[dict[str, Any]]: ...
    async def fetch_page(self, url: str) -> str: ...
    async def health(self) -> bool: ...

class SyncEngine(Protocol):
    async def publish(self, event_id: UUID) -> None: ...
